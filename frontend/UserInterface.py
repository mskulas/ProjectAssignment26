import json
from pathlib import Path
import tkinter as tk
from tkinter import ttk

try:
    # Package-style import: python -m frontend.main
    from ..backend.RunScripts import RunScripts
except ImportError:
    # Script-style import: python frontend/main.py
    import sys

    project_root = Path(__file__).resolve().parent.parent
    if str(project_root) not in sys.path:
        sys.path.insert(0, str(project_root))
    from backend.RunScripts import RunScripts

checkRunning = False
suggestedChangesText = ""
riskLevel = 0

def runSystemCheck():
    global checkRunning, suggestedChangesText, riskLevel
    if not checkRunning:
        checkRunning = True
        print("System check started...")
        RunScripts()
        data = Path(__file__).parent.parent / "backend" / "RunScripts_output.json"
        if data.exists():
            with data.open("r", encoding="utf-8") as file:
                results = json.load(file)
                print("System check results:")
                for name, result in results.items():
                    if result is None:
                        print(f"{name}: No output")
                    elif "error" in result:
                        print(f"{name}: Error - {result['error']}")
                    else:
                        print(f"{name}: {result}")
                    if name == "Firewall profiles":
                        # From this line to line 58, code was partially generated by AI. The code is meant to check the different profiles for firewall enabled status.
                        # Initially, our thinking was to call a .get method on the result, but that method fails on list objects. This code fixes that fault by using
                        # the isinstance method, converting the result to a list and checking whether "Enabled" appears for each profile within.
                        profiles = result if isinstance(result, list) else [result]

                        if not profiles or any(
                            not isinstance(profile, dict) or "Enabled" not in profile
                            for profile in profiles
                        ):
                            itemFailed(firewallProfileLabel)  # missing or unexpected data
                            suggestedChangesText += "Firewall profile check failed. Please review your firewall settings.\n"
                            riskLevel += 1
                        elif any(not profile["Enabled"] for profile in profiles):
                            itemFailed(firewallProfileLabel)
                            suggestedChangesText += "One or more firewall profiles are disabled. Please enable all firewall profiles to ensure your system is protected.\n"
                            riskLevel += 2
                        else:
                           itemPassed(firewallProfileLabel)
                    elif name == "TPM":
                        if result is None or "error" in result:
                            itemFailed(tpmLabel)
                            suggestedChangesText += "TPM check failed. Please ensure your system has TPM enabled and configured correctly.\n"
                            riskLevel += 1
                        elif not result.get("TPMFound", False):
                            itemFailed(tpmLabel)
                            suggestedChangesText += "TPM not found. Unauthorized changes to your system may not be detected. Please ensure your system has TPM enabled and configured correctly.\n"
                            riskLevel += 2
                        else:
                            itemPassed(tpmLabel)
                    elif name == "User privileges":
                        if result is None or "error" in result:
                            itemFailed(userPrivilegesLabel)
                            suggestedChangesText += "User privileges check failed. Please review your user privilege settings.\n"
                            riskLevel += 1
                        elif  result.get("IsAdmin", True):
                            itemPassed(userPrivilegesLabel)
                            suggestedChangesText += "User is an administrator. Use care when making changes to your system."
                        else:
                            itemPassed(userPrivilegesLabel)
                    elif name == "Missing updates":
                        if result is None or "error" in result:
                            itemFailed(missingUpdatesLabel)
                            suggestedChangesText += "Missing updates check failed. Please install all available updates.\n"
                            riskLevel += 1
                        elif result.get("updates"):
                            updates = result["updates"]
                            if updates:
                                itemFailed(missingUpdatesLabel)
                                suggestedChangesText += "Missing updates found. Zero-day exploits may occur against out-of-date devices. Please install all available updates.\n"
                                riskLevel += 2
                            else:
                                itemPassed(missingUpdatesLabel)
                        else:
                            itemPassed(missingUpdatesLabel)
                    elif name == "System log":
                        if result is None or "error" in result:
                            itemFailed(systemLogConfigLabel)
                            suggestedChangesText += "System log configuration check failed. Please review your system log settings.\n"
                            riskLevel += 1
                        else:
                            itemPassed(systemLogConfigLabel)
                    elif name == "System encryption":
                        if result is None or "error" in result:
                            itemFailed(systemEncryptionLabel)
                            suggestedChangesText += "System encryption check failed. Please ensure your system is properly encrypted.\n"
                            riskLevel += 1
                        elif not result.get("bitlockerStatus"):
                            itemFailed(systemEncryptionLabel)
                            suggestedChangesText += "System encryption not found. Your data may be at risk. Please ensure your system is properly encrypted.\n"
                            riskLevel += 1
                        else:
                            itemPassed(systemEncryptionLabel)
                    elif name == "Local user settings":
                        # From this line to line 130, code was partially generated by AI. This code works similarly to the profiles lookup above, except it checks for
                        # local user settings, such as whether local users are present and if password policies are enabled.
                        users = result if isinstance(result, list) else [result]
                        
                        if not users or any(
                            not isinstance(user, dict) or "Enabled" not in user
                            for user in users
                        ):
                            itemFailed(localUserSettingsLabel)  # missing or unexpected data
                            suggestedChangesText += "Local user settings check failed. Please review your local user settings.\n"
                            riskLevel += 1
                        elif any(not user["Enabled"] for user in users):
                            itemFailed(localUserSettingsLabel)
                            suggestedChangesText += "One or more local users are disabled. Please enable all local users to ensure your system is protected.\n"
                            riskLevel += 1
                        elif any(user.get("PasswordRequired", True) is False for user in users):
                            itemFailed(localUserSettingsLabel)
                            suggestedChangesText += "One or more local users do not require a password. Please ensure all local users have password requirements enabled.\n"
                            riskLevel += 2
                        else:
                            itemPassed(localUserSettingsLabel)
        finishSystemCheck()
    else:
        print("System check is already running.")


def finishSystemCheck():
    global checkRunning
    checkRunning = False
    suggestedChangesContent.config(text=str(suggestedChangesText))
    riskLevelLabel.config(text="Risk Level: " + str(riskLevel))
    print("System check finished.")

def itemPassed(label):
    label.config(background="green")
    label.update_idletasks()
    tk.Label(frm, text="Passed").grid(column=1, row=label.grid_info()['row'], sticky='E')

def itemFailed(label):
    label.config(background="red")
    label.update_idletasks()
    tk.Label(frm, text="Failed").grid(column=1, row=label.grid_info()['row'], sticky='E')


root = tk.Tk()
frm = tk.Frame(root, padx=10, pady=10)
frm.grid()
tk.Button(frm, text="Run System Check", command=lambda: runSystemCheck()).grid(column=0, row=0)

firewallProfileLabel = tk.Label(frm, text="Firewall Status")
firewallProfileLabel.grid(column=0, row=1, sticky='W')
tpmLabel = tk.Label(frm, text="TPM Status")
tpmLabel.grid(column=0, row=2, sticky='W')
userPrivilegesLabel = tk.Label(frm, text="User Privileges")
userPrivilegesLabel.grid(column=0, row=3, sticky='W')
missingUpdatesLabel = tk.Label(frm, text="Missing Updates")
missingUpdatesLabel.grid(column=0, row=4, sticky='W')
systemLogConfigLabel = tk.Label(frm, text="System Log Configuration")
systemLogConfigLabel.grid(column=0, row=5, sticky='W')
systemEncryptionLabel = tk.Label(frm, text="System Encryption")
systemEncryptionLabel.grid(column=0, row=6, sticky='W')
localUserSettingsLabel = tk.Label(frm, text="Local User Settings")
localUserSettingsLabel.grid(column=0, row=7, sticky='W')
blankLabel = tk.Label(frm, text="")
blankLabel.grid(column=0, row=8, sticky='W')
suggestedChangesLabel = tk.Label(frm, text="Suggested Changes")
suggestedChangesLabel.grid(column=0, row=9, sticky='W')
suggestedChangesContent = tk.Label(frm, text=str(suggestedChangesText), justify="left", wraplength=400)
suggestedChangesContent.grid(column=0, row=10, columnspan=2, sticky='W')
blankLabel2 = tk.Label(frm, text="")
blankLabel2.grid(column=0, row=11, sticky='W')
riskLevelLabel = tk.Label(frm, text="Risk Level: " + str(riskLevel))
riskLevelLabel.grid(column=0, row=12, sticky='W')

root.mainloop()